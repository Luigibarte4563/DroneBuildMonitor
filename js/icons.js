export function icon(name, cls = "") {
  return `<svg class="icon ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
}

// button arrow that slides on hover
export const arrow = () => `<span class="arrow">${icon("arrow")}${icon("arrow")}</span>`;

// fill <span data-icon="name"> placeholders
export function fillIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    el.innerHTML = icon(el.dataset.icon);
    el.removeAttribute("data-icon");
  });
  root.querySelectorAll("[data-arrow]").forEach((el) => {
    el.insertAdjacentHTML("beforeend", arrow());
    el.removeAttribute("data-arrow");
  });
}
